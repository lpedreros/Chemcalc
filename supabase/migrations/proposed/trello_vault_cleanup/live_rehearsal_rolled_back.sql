-- ---- rehearsal checks (everything below runs inside the same transaction) ----------------------------------------
do $$
declare
  b record;
  u1 uuid := gen_random_uuid();
  u2 uuid := gen_random_uuid();
  k1 uuid;
  t1 uuid;
  n int;
begin
  select * into b from _rh_before;
  -- the existing real profiles are untouched by the trigger and the sweep
  if (select count(*) from public.profiles where trello_api_key_id is not null) <> b.connected
     or (select count(*) from public.profiles) <> b.profiles then
    raise exception 'REHEARSAL_FAILED: the migration changed the number of profiles or connected profiles';
  end if;
  insert into _rh_out(line) values (format('ok  profiles: %s (%s connected) unchanged; vault.secrets: %s before, %s after the sweep',
    b.profiles, b.connected, b.secrets, (select count(*) from vault.secrets)));

  insert into _rh_out(line) values (format('ok  supabase_auth_admin exists: %s; may DELETE auth.users: %s (the real Admin-API path is not exercised by this script)',
    exists (select 1 from pg_roles where rolname = 'supabase_auth_admin'),
    coalesce(has_table_privilege('supabase_auth_admin', 'auth.users', 'DELETE'), false)));

  -- throwaway users; the signup trigger creates their profiles on the real database, make sure either way
  begin
    insert into auth.users (id, email) values (u1, 'rehearsal-' || u1 || '@example.invalid'), (u2, 'rehearsal-' || u2 || '@example.invalid');
  exception when others then
    insert into _rh_out(line) values (format('--  could not create a throwaway auth.users row (SQLSTATE %s): trigger behaviour test skipped', sqlstate));
    return;
  end;
  insert into public.profiles (id, email) values (u1, 'rehearsal-' || u1 || '@example.invalid'), (u2, 'rehearsal-' || u2 || '@example.invalid')
    on conflict (id) do nothing;

  -- user 1 gets (fake) credentials through the real function, as service_role
  set local role service_role;
  if not public.trello_store_credentials(u1, 'REHEARSALKEY' || replace(u1::text, '-', ''), 'REHEARSALTOKEN' || replace(u1::text, '-', '')) then
    reset role;
    raise exception 'REHEARSAL_FAILED: could not store the throwaway credential';
  end if;
  reset role;
  select trello_api_key_id, trello_token_id into k1, t1 from public.profiles where id = u1;
  if k1 is null or t1 is null or (select count(*) from vault.secrets where id in (k1, t1)) <> 2 then
    raise exception 'REHEARSAL_FAILED: throwaway user did not end up with two Vault secrets';
  end if;
  insert into _rh_out(line) values ('ok  throwaway user connected: two Vault secrets exist');

  -- delete both users the way a direct SQL delete would (cascades to profiles, which fires the trigger)
  delete from auth.users where id = u2;
  if exists (select 1 from public.profiles where id = u2) then
    raise exception 'REHEARSAL_FAILED: deleting a user without Trello left the profile behind';
  end if;
  insert into _rh_out(line) values ('ok  deleting a user with no Trello connection: no error, profile cascaded away');

  delete from auth.users where id = u1;
  select count(*) into n from vault.secrets where id in (k1, t1) or name in ('trello_api_key:' || u1, 'trello_token:' || u1);
  if n <> 0 or exists (select 1 from public.profiles where id = u1) then
    raise exception 'REHEARSAL_FAILED: after deleting the connected user, % of its Vault secrets remain (or the profile remains)', n;
  end if;
  insert into _rh_out(line) values ('ok  deleting a Trello-connected user: its two Vault secrets are gone, no error');

  if (select count(*) from public.profiles) <> b.profiles then
    raise exception 'REHEARSAL_FAILED: profile count differs after the throwaway deletes';
  end if;
  insert into _rh_out(line) values (format('ok  profiles back to %s after the throwaway deletes; trigger function executable by anon/authenticated/service_role: %s/%s/%s',
    b.profiles,
    has_function_privilege('anon', 'public.trello_cleanup_vault_on_profile_delete()'::regprocedure, 'EXECUTE'),
    has_function_privilege('authenticated', 'public.trello_cleanup_vault_on_profile_delete()'::regprocedure, 'EXECUTE'),
    has_function_privilege('service_role', 'public.trello_cleanup_vault_on_profile_delete()'::regprocedure, 'EXECUTE')));
end $$;

-- ---- the deliberate error: report and abort --------------------------------------------------------------------------
do $$
begin
  raise exception 'REHEARSAL_ROLLBACK (deliberate, nothing committed):%', E'\n' || (select string_agg(line, E'\n' order by n) from _rh_out);
end $$;

rollback;   -- only reached by a client that keeps going after the error
