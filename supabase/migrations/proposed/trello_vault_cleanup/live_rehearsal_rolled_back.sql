--
-- WHAT IT IS: the full 20261009230000_trello_vault_cleanup_on_profile_delete.sql body followed by end-to-end checks, all
-- inside ONE transaction that ends in a deliberate error, so NOTHING COMMITS. Expected outcome: ERROR starting
-- "REHEARSAL_ROLLBACK (deliberate, nothing committed)" followed by one line per check, all "ok" (or "--" for a documented
-- skip). Any line starting "REHEARSAL_FAILED" means a check failed (that also changes nothing).
--
-- WHAT IT TOUCHES: it never reads or changes Leo's Trello credential. It creates two THROWAWAY users (auth.users rows with
-- random uuids and fake credential-shaped values), stores fake credentials for one, deletes both users and checks the trigger
-- removed exactly that user's secrets. All of it is rolled back. The migration's one-time sweep also runs inside the
-- transaction; the number of orphans it would remove is reported (a count, no names or values).
-- It takes brief locks on public.profiles and auth.users. NO CREDENTIAL VALUE IS PRINTED.
--
-- LIMIT: from the SQL editor (role postgres, not a superuser) this script cannot become supabase_auth_admin, the role Supabase
-- Auth deletes users with, so the Admin-API path is NOT exercised here (the local replica tests emulate it with SET SESSION
-- AUTHORIZATION). After any real apply, delete a throwaway test user through the Admin API as the first live check (REPORT.md).
-- Generated by test/build_rehearsal.mjs: the block between the BODY markers is the migration, byte for byte.
-- ============================================================================
begin;

create temp table _rh_out (n serial, line text) on commit drop;
create temp table _rh_before on commit drop as
  select (select count(*) from vault.secrets) as secrets,
         (select count(*) from public.profiles) as profiles,
         (select count(*) from public.profiles where trello_api_key_id is not null) as connected;

